"""现成资源的【摆位修正表】—— 把散落的零件摆回该有的位置。

【为什么需要】
  Polyhaven 的资源是"产品陈列图"：同一个物件的多个变体
  （全新 / 生锈）会并排放在一起，零件（盖子、把手、说明书）
  常常是【侧躺或斜靠】在主体旁边的。

  直接拿整组的包围盒去拟合目标尺寸，会出现这种结果：
    metal_trash_can（全新+生锈两个垃圾桶并排，盖子侧躺 75°）
      整组包围盒 = 613 × 556 × 1185mm
      拟合到 300×300×600 的垃圾桶 → 桶身只剩 495mm 高（应为 600mm）
      → 用户看到的比例就是崩的。

  正确做法：只保留要用的那一个变体，并把侧躺的盖子【摆回桶口】。
  这是对现成资源做【摆位修正】，不涉及重新建模，
  零件的真实几何、材质、细节全部保留。

【条目格式】
  "<资源 id>": {
      "keep":      ["节点名", ...],       # 保留哪些节点（None = 全保留）
      "transform": {"节点名": {...}},      # 覆盖该节点的位移/旋转
  }
"""
import math


def qz(angle_deg):
    """绕 Z 轴转 angle 度的四元数 [x,y,z,w]。"""
    a = math.radians(angle_deg) / 2
    return [0.0, 0.0, math.sin(a), math.cos(a)]


